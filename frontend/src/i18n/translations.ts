export function getProductName(product: { name_en: string; name_fr: string; name_ar: string }, locale: Locale) {
  if (locale === 'fr') return product.name_fr;
  if (locale === 'ar') return product.name_ar;
  return product.name_en;
}

export function getProductDescription(
  product: { description_en: string | null; description_fr: string | null; description_ar: string | null },
  locale: Locale,
) {
  if (locale === 'fr') return product.description_fr;
  if (locale === 'ar') return product.description_ar;
  return product.description_en;
}
